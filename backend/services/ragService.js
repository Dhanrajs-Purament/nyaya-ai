import { generateResponse, streamResponse } from './ollamaService.js';
import { formatEvidenceWithTags, validateCitations } from './citationService.js';

export const SYSTEM_PROMPT = `You are a document-grounded AI assistant.
Your task is to answer questions using only the supplied retrieved context.

Rules:
1. Use only the provided document context to answer factual questions.
2. Do not invent facts, statistics, dates, names, or explanations.
3. Do not rely on outside knowledge when answering document-specific questions.
4. If the retrieved context is insufficient, explicitly state that the documents do not contain enough information.
5. Distinguish clearly between directly stated information and reasonable interpretations.
6. Attach source identifiers like [S1], [S2] to factual claims.
7. Never fabricate citations.
8. If sources contradict each other, explain the disagreement and cite both sources.
9. Do not present uncertain conclusions as established facts.
10. Keep answers clear, structured, and relevant to the user's question.`;

/**
 * Builds the user prompt incorporating tagged context [S1], [S2]...
 */
export function buildGroundedPrompt(question, taggedText) {
  return `DOCUMENT CONTEXT EVIDENCE:
${taggedText}

USER QUESTION:
${question}

GROUNDED ANSWER WITH [S1], [S2]... CITATIONS:`;
}

/**
 * Model Adapter: Receives an immutable retrieval result object and executes generation.
 * (Model adapters NEVER call the retrieval function themselves).
 * 
 * @param {string} model Model identifier (e.g. 'gemma3:4b')
 * @param {object} retrievalResult Structured output from retrievalService.js
 * @param {object} options Additional options (customSystemPrompt)
 */
export async function executeGroundedModel(model, retrievalResult, options = {}) {
  const startTime = Date.now();
  const { taggedText, sourceMap } = formatEvidenceWithTags(retrievalResult.chunks || []);
  const userPrompt = buildGroundedPrompt(retrievalResult.question, taggedText);
  const systemPrompt = options.systemPrompt || SYSTEM_PROMPT;

  // Run model inference via Ollama
  const inference = await generateResponse(model, userPrompt, systemPrompt);
  const totalDurationMs = Date.now() - startTime;

  // Validate citations generated by the model against retrieved sources
  const citationAnalysis = validateCitations(inference.response || '', sourceMap);

  return {
    model,
    success: inference.success,
    response: inference.response,
    error: inference.error,
    metrics: {
      ...inference.metrics,
      retrievalDurationMs: retrievalResult.durationMs,
      totalDurationMs
    },
    citations: {
      validation: citationAnalysis,
      retrievedChunks: retrievalResult.chunks
    }
  };
}

/**
 * Streaming Model Adapter: Streams tokens for a single model given a retrieval result.
 */
export async function executeGroundedModelStream(model, retrievalResult, onToken, signal, options = {}) {
  const { taggedText, sourceMap } = formatEvidenceWithTags(retrievalResult.chunks || []);
  const userPrompt = buildGroundedPrompt(retrievalResult.question, taggedText);
  const systemPrompt = options.systemPrompt || SYSTEM_PROMPT;

  const result = await streamResponse(model, userPrompt, systemPrompt, onToken, signal);
  const citationAnalysis = validateCitations(result.response || '', sourceMap);

  return {
    ...result,
    citations: {
      validation: citationAnalysis,
      retrievedChunks: retrievalResult.chunks
    }
  };
}
